/**
 * Generates the text of dist/sw.js. The worker is hand-written (no
 * dependencies) and generated at build time because it embeds the precache
 * list. Strategy selection lives in strategy.ts and is inlined here, so the
 * tested function is the one that runs.
 *
 *   install   : open cache "explosive-endurance-<hash>" (hash of the files'
 *               bytes) and add every precache URL, each fetched with
 *               {cache: "reload"} so the HTTP cache can't supply stale files
 *   message   : {type: "SKIP_WAITING"} from the page -> skipWaiting()
 *               (the only place the worker takes over early)
 *   activate  : delete every other "explosive-endurance-*" cache
 *               (no clients.claim: pages loaded before it keep their worker)
 *   fetch     : chooseStrategy(request)
 *                 ignore        -> browser default
 *                 shell         -> page load: this version's cached "./";
 *                                  network only if it is missing;
 *                                  the response is NEVER written to the cache
 *                 network-first -> program.json: fetch({cache: "no-cache"});
 *                                  if ok and JSON, cache a copy; on failure
 *                                  (or a bad response) the cached copy
 *                 cache-first   -> precached copy, else plain network fetch;
 *                                  nothing is ever added to the cache
 *
 *   page (register.ts)            worker
 *   ------------------            ------
 *   launch, update waiting? --SKIP_WAITING--> skipWaiting() -> activate
 *   controllerchange <------------------------ (new worker in charge)
 *   reload once (sessionStorage guard)
 *
 * Why updates only apply at launch: swapping the worker (and so possibly the
 * code a page loads) in the middle of a workout session could mix old and new
 * files. A new version installs in the background and waits; the next launch
 * asks it to take over before anything is on screen.
 */

import { chooseStrategy } from "./strategy.ts";

/**
 * Renders sw.js for a build.
 *
 * @param cacheName versioned cache name from `buildCacheName`
 * @param precacheUrls relative URLs to cache at install
 */
export function renderServiceWorker(cacheName: string, precacheUrls: string[]): string {
  return `// Generated by the build (src/pwa/serviceWorkerSource.ts). Do not edit.
const CACHE_NAME = ${JSON.stringify(cacheName)};
const CACHE_PREFIX = "explosive-endurance-";
const PRECACHE_URLS = ${JSON.stringify(precacheUrls)};
${chooseStrategy.toString()}

self.addEventListener("install", (event) => {
  // cache: "reload" skips the HTTP cache, so every precached file is exactly
  // what the server has now (not a stale copy from an earlier visit).
  const requests = PRECACHE_URLS.map((url) => new Request(url, { cache: "reload" }));
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(requests)));
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map((name) => caches.delete(name))),
    ),
  );
});

// Page loads: always the shell precached with this worker version. The
// response of a page load is never cached, so a stray URL or a deploy that
// has only half arrived can't overwrite the shell.
async function serveShell(request) {
  const cache = await caches.open(CACHE_NAME);
  const shell = await cache.match("./", { ignoreVary: true });
  return shell || fetch(request);
}

// program.json: the network wins when it gives a good JSON answer (and the
// cache is refreshed); anything else falls back to the last good copy.
async function programNetworkFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request, { cache: "no-cache" });
    const contentType = response.headers.get("content-type") || "";
    if (response.ok && contentType.includes("json")) {
      await cache.put(request, response.clone());
      return response;
    }
    const cached = await cache.match(request, { ignoreVary: true });
    return cached || response;
  } catch (error) {
    const cached = await cache.match(request, { ignoreVary: true });
    if (cached) {
      return cached;
    }
    throw error;
  }
}

// Everything else: the precached copy (ignoreVary: the precache requests carry
// no Origin header, so a "Vary: Origin" response would otherwise never match
// a module-script request). If it isn't there, a plain fetch that is not
// stored (only the precache list ever lives in the cache).
async function precachedFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request, { ignoreVary: true });
  return cached || fetch(request);
}

self.addEventListener("fetch", (event) => {
  const strategy = chooseStrategy(event.request, self.location.origin);
  if (strategy === "shell") {
    event.respondWith(serveShell(event.request));
  } else if (strategy === "network-first") {
    event.respondWith(programNetworkFirst(event.request));
  } else if (strategy === "cache-first") {
    event.respondWith(precachedFirst(event.request));
  }
});
`;
}
