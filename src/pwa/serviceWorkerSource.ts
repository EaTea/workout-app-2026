/**
 * Generates the text of dist/sw.js. The worker is hand-written (no
 * dependencies) and generated at build time because it embeds the precache
 * list. Strategy selection lives in strategy.ts and is inlined here, so the
 * tested function is the one that runs.
 *
 *   install   : open cache "explosive-endurance-<hash>", add every precache URL
 *               (no skipWaiting: the new worker waits)
 *   activate  : delete every other "explosive-endurance-*" cache
 *               (no clients.claim: open pages keep their worker)
 *   fetch     : chooseStrategy(request)
 *                 ignore        -> browser default
 *                 network-first -> fetch; on success cache a copy, return it;
 *                                  on failure return the cached copy
 *                                  (navigations fall back to "./")
 *                 cache-first   -> cached copy, else fetch and cache it
 *
 * Why no skipWaiting / clients.claim: swapping the worker (and so possibly
 * the code a page loads) in the middle of a workout session could mix old
 * and new files. A new version takes over on the next launch, once every
 * tab using the old one is closed.
 */

import { chooseStrategy } from "./strategy";

/**
 * Renders sw.js for a build.
 *
 * @param cacheName versioned cache name from `buildCacheName`
 * @param precacheUrls relative URLs to cache at install
 */
export function renderServiceWorker(cacheName: string, precacheUrls: string[]): string {
  return `// Generated by the build (src/pwa/serviceWorkerSource.ts). Do not edit.
const CACHE_NAME = ${JSON.stringify(cacheName)};
const CACHE_PREFIX = "explosive-endurance-";
const PRECACHE_URLS = ${JSON.stringify(precacheUrls)};
${chooseStrategy.toString()}

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map((name) => caches.delete(name))),
    ),
  );
});

async function networkFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request);
    if (response.ok) {
      await cache.put(request.mode === "navigate" ? "./" : request, response.clone());
    }
    return response;
  } catch (error) {
    const cached = (await cache.match(request)) || (request.mode === "navigate" ? await cache.match("./") : undefined);
    if (cached) {
      return cached;
    }
    throw error;
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request);
  if (cached) {
    return cached;
  }
  const response = await fetch(request);
  if (response.ok) {
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const strategy = chooseStrategy(event.request, self.location.origin);
  if (strategy === "network-first") {
    event.respondWith(networkFirst(event.request));
  } else if (strategy === "cache-first") {
    event.respondWith(cacheFirst(event.request));
  }
});
`;
}
